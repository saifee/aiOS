// Generates packages/db/prisma/schema.sql (idempotent MySQL/MariaDB DDL) from schema.prisma.
// Why: lets a host with no Prisma CLI (e.g. Hostinger "no npm install" package) create the tables
// by running plain SQL (via phpMyAdmin, or automatically on first boot).
import { readFileSync, writeFileSync } from "fs";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const wasm = require("@prisma/prisma-schema-wasm");

const schemaPath = "packages/db/prisma/schema.prisma";
const dmmf = JSON.parse(wasm.get_dmmf(JSON.stringify({ prismaSchema: readFileSync(schemaPath, "utf8"), noColor: true }))).datamodel;
const enums = new Map(dmmf.enums.map((e) => [e.name, e.values.map((v) => v.name)]));
const q = (s) => "`" + s + "`";
const lit = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "''") + "'";

function colType(f) {
  if (f.kind === "enum") return `ENUM(${enums.get(f.type).map(lit).join(",")})`;
  const native = f.nativeType?.[0];
  switch (f.type) {
    case "String": return native === "Text" ? "TEXT" : native === "VarChar" ? `VARCHAR(${f.nativeType[1][0]})` : "VARCHAR(191)";
    case "Int": return "INTEGER";
    case "BigInt": return "BIGINT";
    case "Float": return "DOUBLE";
    case "Decimal": return "DECIMAL(65,30)";
    case "Boolean": return "BOOLEAN";
    case "DateTime": return "DATETIME(3)";
    case "Json": return "JSON";
    case "Bytes": return "LONGBLOB";
    default: throw new Error(`unmapped type ${f.type} on ${f.name}`);
  }
}
function colDefault(f, type) {
  if (!f.hasDefaultValue || f.default === undefined) return "";
  const d = f.default;
  if (typeof d === "object" && !Array.isArray(d)) {
    if (d.name === "autoincrement") return " AUTO_INCREMENT";
    if (d.name === "now") return " DEFAULT CURRENT_TIMESTAMP(3)";
    return ""; // cuid()/uuid() are generated by the Prisma client
  }
  if (type === "JSON") return ` DEFAULT (${lit(JSON.stringify(Array.isArray(d) ? d : typeof d === "string" ? JSON.parse(d) : d))})`;
  if (type === "TEXT") return "";
  if (typeof d === "boolean") return ` DEFAULT ${d ? 1 : 0}`;
  if (typeof d === "number") return ` DEFAULT ${d}`;
  return ` DEFAULT ${lit(d)}`;
}
const refAction = (a, optional) => ({ Cascade: "CASCADE", Restrict: "RESTRICT", NoAction: "NO ACTION", SetNull: "SET NULL", SetDefault: "SET DEFAULT" }[a] ?? (optional ? "SET NULL" : "RESTRICT"));

// Topological order so every FK target already exists
const deps = new Map(dmmf.models.map((m) => [m.name, new Set(m.fields.filter((f) => f.relationFromFields?.length && f.type !== m.name).map((f) => f.type))]));
const ordered = [], done = new Set();
while (ordered.length < dmmf.models.length) {
  const next = dmmf.models.filter((m) => !done.has(m.name) && [...deps.get(m.name)].every((d) => done.has(d)));
  if (!next.length) { for (const m of dmmf.models) if (!done.has(m.name)) { ordered.push(m); done.add(m.name); } break; }
  for (const m of next) { ordered.push(m); done.add(m.name); }
}

const out = [`-- Generated by scripts/gen-mysql-sql.mjs from packages/db/prisma/schema.prisma — do not edit by hand.\n-- Idempotent: safe to run more than once. Works on MySQL 8 and MariaDB 10.4+.\n`];
for (const m of ordered) {
  const lines = [];
  for (const f of m.fields) {
    if (f.kind === "object") continue;
    const t = colType(f);
    lines.push(`  ${q(f.name)} ${t} ${f.isRequired ? "NOT NULL" : "NULL"}${colDefault(f, t)}`);
  }
  for (const ix of dmmf.indexes.filter((i) => i.model === m.name)) {
    const cols = ix.fields.map((x) => q(x.name)).join(", ");
    const nm = q(`${m.name}_${ix.fields.map((x) => x.name).join("_")}_${ix.type === "unique" ? "key" : "idx"}`);
    if (ix.type === "id") lines.push(`  PRIMARY KEY (${cols})`);
    else if (ix.type === "unique") lines.push(`  UNIQUE INDEX ${nm} (${cols})`);
    else if (ix.type === "normal") lines.push(`  INDEX ${nm} (${cols})`);
  }
  for (const f of m.fields.filter((f) => f.relationFromFields?.length)) {
    lines.push(`  CONSTRAINT ${q(`${m.name}_${f.relationFromFields.join("_")}_fkey`)} FOREIGN KEY (${f.relationFromFields.map(q).join(", ")}) REFERENCES ${q(f.type)} (${f.relationToFields.map(q).join(", ")}) ON DELETE ${refAction(f.relationOnDelete, !f.isRequired)} ON UPDATE CASCADE`);
  }
  out.push(`CREATE TABLE IF NOT EXISTS ${q(m.name)} (\n${lines.join(",\n")}\n) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n`);
}
writeFileSync("packages/db/prisma/schema.sql", out.join("\n"));
console.log(`wrote packages/db/prisma/schema.sql — ${ordered.length} tables`);
